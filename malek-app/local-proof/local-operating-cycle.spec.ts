import { test, expect } from '@playwright/test';
const api = process.env.VITE_SUPABASE_URL!;
if (new URL(api).hostname !== '127.0.0.1') throw new Error('Loopback only');
const publicKey = process.env.VITE_SUPABASE_ANON_KEY!;
const evidence = process.env.LOCAL_PROOF_EVIDENCE_DIR ?? 'test-results/local-proof-evidence';
test('real local collection, receipt and owner statement', async ({ page }) => {
  test.setTimeout(90000);
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('/login');
  await page.getByRole('textbox',{name:'البريد الإلكتروني',exact:true}).fill('local-maker@malek.test');
  await page.getByPlaceholder('••••••••').fill('local-fixture-not-for-production-2026');
  await page.getByRole('button',{name:/تسجيل الدخول/}).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  const session = await page.evaluate(() => JSON.parse(localStorage.getItem('malek-auth-session')!));
  const headers={apikey:publicKey,Authorization:`Bearer ${session.access_token}`};
  const invoiceRows=await (await page.request.get(`${api}/rest/v1/invoices?select=id,amount,paid_amount,contract_id,status&limit=20`,{headers})).json();
  const invoice=invoiceRows.find((row: {amount: number; paid_amount: number}) => Number(row.amount)-Number(row.paid_amount)>1);expect(invoice).toBeTruthy();
  const reference=`Local UI collection ${Date.now()}`;
  await page.goto(`/financials?section=collections&view=invoices&invoiceId=${invoice.id}&collect=1`);
  await expect(page.locator('#quick-payment-amount')).toBeVisible();
  await page.locator('#quick-payment-amount').fill('0.123');
  await page.locator('#quick-payment-reference').fill(reference);
  await page.locator('#quick-payment-form').getByRole('button',{name:'تسجيل دفعة',exact:true}).click();
  await expect(page.getByText('تم تسجيل الدفعة بنجاح',{exact:true}).first()).toBeVisible();
  const payments=await (await page.request.get(`${api}/rest/v1/payments?select=id,amount&reference_no=eq.${encodeURIComponent(reference)}`,{headers})).json();
  expect(payments).toHaveLength(1);expect(Number(payments[0].amount)).toBe(0.123);
  await page.goto(`/receipts?receiptId=${payments[0].id}`);
  await expect(page.getByRole('heading',{name:'إيصال استلام نقدية',exact:true,level:1})).toBeVisible();
  await expect(page.getByText(/0\.123/).first()).toBeVisible();
  await page.reload();
  await expect(page.getByText(/0\.123/).first()).toBeVisible();
  await page.screenshot({path:`${evidence}/real-new-receipt.png`,fullPage:true});
  const owner='00000000-0000-4000-8100-000000000001';
  await page.goto(`/owners/${owner}`);
  await page.getByRole('tab',{name:'الموقف المالي',exact:true}).click();
  await expect(page.locator('[data-owner-financial-authority]')).toBeVisible();
  await page.getByText('ملخص كشف حساب الفترة',{exact:true}).click();
  await expect(page.getByText('إجمالي الكشف',{exact:true})).toBeVisible();
  await page.screenshot({path:`${evidence}/real-owner-statement.png`,fullPage:true});
  await page.goto(`/reports/owner-comprehensive-statement?view=statement&ownerId=${owner}`);
  await expect(page.locator('[data-report-product-page="owner-comprehensive-statement"]')).toBeVisible();
  await expect(page.locator('[data-report-product-page="owner-comprehensive-statement"] .skeleton-shimmer')).toHaveCount(0, {timeout:20000});
  await page.screenshot({path:`${evidence}/real-owner-statement-report.png`,fullPage:true});
});
