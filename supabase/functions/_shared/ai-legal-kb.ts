export const LEGAL_KB_COUNTRIES: readonly LegalKbCountry[] = [OMAN_LEGAL, SAUDI_LEGAL] as const;

export function findLegalCountry(countryId?: string): LegalKbCountry {
  return (
    LEGAL_KB_COUNTRIES.find((country) => country.id === countryId) ?? LEGAL_KB_COUNTRIES[0]
  );
}

export function renderLegalText(countryId?: string): string {
  const country = findLegalCountry(countryId);
  const sections = country.sections.map((s) => `${s.title}\n${s.body}`).join("\n\n");
  const instruments = country.instrumentsAr.join("؛ ");
  const text = `
قاعدة مرجعية قانونية/نظامية لسوق ${country.nameAr} (قراءة إرشادية من مصادر تشريعية عامة — ليست استشارة قانونية أو نصاً معتمداً؛ يُراجع دائمًا نص القانون/اللائحة والجهة المختصة):

الأدوات التشريعية الحاكمة ($country.nameAr):
${instruments}

الأقسام:
${sections}

تنويه إلزامي: هذه قراءة إرشادية موجزة وليست استشارة قانونية؛ راجع النص الرسمي للقانون/اللائحة والجهة المختصة قبل أي قرار.
`.trim();
  if (text.length > LEGAL_KB_MAX_CHARS) {
    throw new Error(
      `Legal KB rendering exceeds budget: ${text.length} > ${LEGAL_KB_MAX_CHARS}`,
    );
  }
  return text;
}

/** Backward-compatible default render. */
export const LEGAL_KB_TEXT = renderLegalText();
